# Пример на Python — kafka-python или confluent-kafka
# Producer — отправка сообщения

from kafka import KafkaProducer
import json

producer = KafkaProducer(
    bootstrap_servers='localhost:9092',
    value_serializer=lambda v: json.dumps(v).encode('utf-8')
)


def create_order(order_data):
   # save_order(order_data)  # сохранили в свою БД

    # Публикуем событие — и ВСЁ, не ждём, кто и как его обработает
    producer.send('order_created', {
        'order_id': order_data['id'],
        'user_id': order_data['user_id'],
        'amount': order_data['amount']
    })
    producer.flush()

    return {"status": "order created"}


# Consumer — чтение сообщений (отдельный сервис/процесс)

