'''
__slots__ — это механизм Python, который позволяет заранее определить, какие атрибуты могут существовать у экземпляров класса.
Главная цель — уменьшить потребление памяти и ограничить набор атрибутов объекта.
Разберём по шагам.
1. Как Python хранит атрибуты без __slots__
По умолчанию экземпляры обычных классов имеют __dict__ — словарь, в котором хранятся их атрибуты.

'''


class User:
    def __init__(self, name, age):
        self.name = name
        self.age = age


user = User("Denis", 30)

print(user.__dict__)
# {'name': 'Denis', 'age': 30}

# И благодаря этому мы можем динамически добавлять новые атрибуты:
user.email = "test@example.com"
user.is_active = True

# 2. Что меняется при использовании __slots__

class User:
    __slots__ = ("name", "age")

    def __init__(self, name, age):
        self.name = name
        self.age = age


user = User("Denis", 30)

print(user.name)  # Denis
print(user.age)   # 30

user.email = "test@example.com" # AttributeError

# 3. Почему это экономит память?

# Без __slots__ каждый экземпляр обычно использует словарь для хранения атрибутов.
# С __slots__ Python может хранить значения атрибутов в заранее определённых слотах, без отдельного словаря экземпляра.

# При обычном классе Python обращается к атрибутам через механизм словаря (с учётом внутренних оптимизаций CPython).
# При __slots__ доступ к атрибутам может быть эффективнее благодаря заранее определённым слотам.
