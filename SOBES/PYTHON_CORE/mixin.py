"""
Mixin — это класс, который не предназначен для самостоятельного использования (не создают его экземпляры напрямую),
а добавляется в другие классы через множественное наследование, чтобы "подмешать" (mix in) конкретную функциональность.

Основная идея: вместо одного "толстого" класса с кучей несвязанной логики — собираем нужное поведение из
маленьких независимых кусочков.



Признаки хорошего mixin
Не имеет собственного __init__ с обязательными аргументами (или вообще не имеет __init__).
Не предполагает самостоятельного инстанцирования — его смысл только в комбинации с другим классом.
Обычно называется с суффиксом Mixin (конвенция, не требование языка).
Решает одну узкую задачу (принцип единственной ответственности).
Где встречается в реальности

Классический пример — Django: LoginRequiredMixin, PermissionRequiredMixin в class-based views:

python
class MyView(LoginRequiredMixin, View):
    def get(self, request):
        ...

Здесь LoginRequiredMixin не содержит логики самой view — он просто добавляет проверку авторизации перед вызовом get/post
через переопределение dispatch.

Другой пример из стандартной библиотеки — socketserver.ThreadingMixIn, который подмешивает многопоточность к серверу.

Как это работает технически

Mixin реализуется через MRO (Method Resolution Order) — порядок, в котором Python ищет метод по цепочке наследования
при множественном наследовании. Порядок родителей в class Dog(JSONMixin, ComparableMixin): имеет значение — именно он
определяет, чей метод найдётся первым, если имена пересекаются (можно проверить через Dog.__mro__ или Dog.mro()).

Mixin vs обычное наследование
Обычное наследование: “Dog является Animal” (is-a отношение).
Mixin: “Dog умеет превращаться в JSON” (has-ability отношение) — это не про иерархию сущностей, а про добавление возможности.

На собесе полезно упомянуть: mixin — это паттерн композиции через наследование, Python поддерживает его естественно
благодаря множественному наследованию (в отличие от Java, где для этого нужны интерфейсы с default-методами).
"""

class JSONMixin:
    def to_json(self):
        import json
        return json.dumps(self.__dict__)

class ComparableMixin:
    def __eq__(self, other):
        return self.__dict__ == other.__dict__

class Dog(JSONMixin, ComparableMixin):
    def __init__(self, name):
        self.name = name

d = Dog('Jado')
d.to_json()
