'''
MRO (Method Resolution Order) — простыми словами

Проблема: когда у класса несколько родителей (множественное наследование), и у разных родителей есть метод с
одинаковым именем — какой из них вызовется?


Python читает это как список приоритетов: сначала ищет greet в D (нет), потом в B (есть! → берём) — и останавливается, дальше не идёт.

Правило "сверху вниз, слева направо, но без повторов" (алгоритм C3)

Главное, что нужно запомнить на уровне интуиции:

Сам класс всегда первый.
Родители идут в том порядке, в котором вы их написали в class D(B, C): — сначала всё от B, потом всё от C.
Общий предок (A) откладывается до конца — Python не идёт в A сразу после B, потому что C тоже наследуется от A,
и если уйти в A раньше, можно "потерять" переопределения в C.


'''



class A:
    def greet(self):
        print("A")

class B(A):
    def greet(self):
        print("B")

class C(A):
    def greet(self):
        print("C")

class D(B, C):
    pass

d = D()
d.greet()   # что выведет?



# print(D.__mro__)
# # или
# print(D.mro())
#
# # (<class 'D'>, <class 'B'>, <class 'C'>, <class 'A'>, <class 'object'>)









# Где MRO реально "кусает" на практике — super()
# Важный момент: super() в B не вызывает A.greet() напрямую.
# Он вызывает "следующий класс по MRO этого конкретного объекта" — а так как объект — D, и MRO у него D → B → C → A, то из
# Bsuper() ведёт в C, а не в A!
# Это именно то, что делает mixin('ы рабочими — каждый класс в цепочке вызывает super(), '
# и срабатывает вся цепочка по порядку, а не "срезает" половину.)


class A:
    def greet(self):
        print("A")

class B(A):
    def greet(self):
        print("B")
        super().greet()   # вызовет СЛЕДУЮЩИЙ по MRO, а не "родителя B конкретно"

class C(A):
    def greet(self):
        print("C")
        super().greet()

class D(B, C):
    def greet(self):
        print("D")
        super().greet()

D().greet()
# D
# B
# C
# A














