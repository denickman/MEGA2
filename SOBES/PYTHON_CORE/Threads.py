import threading
import time

'''
Пояснения:

threading.Thread(target=worker, args=(...)) — создаёт поток, но ещё не запускает его. args — это аргументы, 
с которыми будет вызвана функция worker.
.start() — реально запускает поток (он начинает выполняться параллельно с основным кодом).
Так как внутри worker используется time.sleep() (ожидание, I/O-подобная операция) — 
GIL здесь не мешает: пока поток “A” спит 2 секунды, поток “B” спокойно работает. 

Поэтому весь скрипт выполнится примерно за 4 секунды (время самого долгого потока), а не за 2+4=6.

.join() — говорит главному потоку: "подожди, пока этот поток закончится, прежде чем идти дальше". 

Без join() строка print("Все потоки завершены") могла бы напечататься раньше, чем реально завершатся t1/t2.
'''

# Функция, которую будем выполнять в потоке
def worker(name, delay):
    print(f"Поток {name} запущен")
    time.sleep(delay)
    print(f"Поток {name} завершён")

# Создание потоков
t1 = threading.Thread(target=worker, args=("A", 2))
t2 = threading.Thread(target=worker, args=("B", 4))

# Запуск потоков
t1.start()
t2.start()

# Ожидание завершения потоков
t1.join()
t2.join()
print("Все потоки завершены")









'''
Пояснения:

ThreadPoolExecutor — это более удобная "обёртка" над потоками. Вместо того чтобы вручную создавать Thread, 
вызывать .start(), .join() для каждого — ты просто говоришь: "вот у меня пул из 4 потоков, прогони через них эти 5 задач".
max_workers=4 — одновременно работает максимум 4 потока. Так как задач 5, а воркеров 4, один элемент (пятый) подождёт, 
пока освободится поток.

executor.map(work, [1, 2, 3, 4, 5]) — аналог обычного map(), только каждый вызов work(x) выполняется в отдельном потоке пула, 
а не последовательно. Результаты возвращаются в том же порядке, в котором были переданы аргументы 
(даже если потоки завершились в другом порядке).

with ... as executor: — контекстный менеджер (помнишь, обсуждали @contextmanager?) — он сам аккуратно дожидается 
завершения всех потоков и "закрывает" пул при выходе из блока, так что вручную join() вызывать не нужно.
Благодаря time.sleep(1) внутри (ожидание, не вычисление) — 5 задач выполнятся не за 5 секунд, а примерно за 2 
(сначала 4 параллельно по 1 сек, потом ещё 1 задача — ещё 1 сек).

Важно: ThreadPoolExecutor — это всё та же конкурентность через потоки (с тем же GIL), просто удобный интерфейс. 
Если бы work не спал, а реально что-то тяжело вычислял, выигрыша по скорости почти не было бы — 
для этого есть ProcessPoolExecutor (аналог, но на процессах, с настоящим параллелизмом).
'''











import time
from concurrent.futures import ThreadPoolExecutor

def work(x: int) -> int:
    time.sleep(1)
    return x * x

# 4 потока исполняют функцию work
with ThreadPoolExecutor(max_workers=4) as executor:
    results = list(executor.map(work, [1, 2, 3, 4, 5]))

print(results)  # [1, 4, 9, 16, 25]