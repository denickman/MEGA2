
'''
Отличие от обычного @property: обычный @property каждый раз заново выполняет код геттера при обращении.
cached_property выполняет его один раз, а результат кладёт прямо в __dict__ объекта под тем же именем.
При следующем обращении Python сначала смотрит в __dict__ объекта (как обычный атрибут) и находит
 там уже готовое значение — метод вообще не вызывается снова.


Зачем: когда вычисление дорогое (тяжёлый запрос, сложная агрегация),
а результат не меняется после первого расчёта.

Важный нюанс: раз результат лежит в __dict__, объект должен иметь __dict__ — то есть cached_property не
работает с __slots__ без явного добавления __dict__ в слоты.

'''
from functools import cached_property

class Report:
    @cached_property
    def heavy_calculation(self):
        print("Counting.....")
        return sum(range(10**7))

r = Report()
r.heavy_calculation  # считаю... → 49999995000000
r.heavy_calculation  # (тишина) → 49999995000000, из кэша



