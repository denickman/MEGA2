'''
Корутина (coroutine) — это функция, которая может приостанавливать свое выполнение и возобновлять его позже,
сохраняя своё состояние (локальные переменные, точку выполнения) между приостановками.
В этом принципиальное отличие от обычной функции, которая либо выполняется целиком, либо не выполняется вовсе.


Coroutine vs Task в asyncio
Это разные уровни абстракции одной и той же асинхронной операции.


Coroutine — "рецепт", сам по себе не выполняется параллельно

Как обсуждали выше — вызов async def функции создаёт объект-корутину, который просто описывает что нужно сделать.
Сама по себе корутина не планируется на выполнение event loop'ом, пока её явно не await-нули или не обернули в Task.






'''

